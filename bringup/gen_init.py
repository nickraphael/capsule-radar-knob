#!/usr/bin/env python3
"""Generate bringup/st77916_knob_init.h from Waveshare's demo (lcd_bsp.c).

Why a generator and not a committed header: Waveshare's demo ships no license file,
so the vendor init table is NOT committed (the generated header is git-ignored).
This script is ours; it only reads the demo you point it at. It also avoids
hand-transcribing ~100 register writes.

Usage (from the project root):
  python bringup/gen_init.py "<demo>\\Arduino\\examples\\08_LVGL_Test\\lcd_bsp.c"

What it reproduces, in the demo's order (verified against the demo's esp_lcd wrapper):
  1. MADCTL 0x36 = 0x00   (wrapper sends this before the vendor table; RGB order)
  2. COLMOD 0x3A = 0x55   (wrapper sends this before the vendor table; 16 bpp)
  3. every entry of lcd_init_cmds[] verbatim: command, its parameter bytes
     (including the spurious 0x00 the demo sends after 0x21/0x11/0x29), then a delay
The #ifdef EXAMPLE_Rotate_90 branch is skipped (the non-rotated #else branch is used).
Output is in Arduino_GFX's batch-operation format, for Arduino_ST77916's constructor.
"""
import hashlib
import pathlib
import re
import sys

ENTRY = re.compile(
    r'^\{\s*0x([0-9A-Fa-f]{2})\s*,\s*\(uint8_t\s*\[\]\)\s*\{([^}]*)\}\s*,\s*(\d+)\s*,\s*(\d+)\s*\}\s*,?\s*(//.*)?$'
)


def die(msg):
    print("gen_init.py: " + msg, file=sys.stderr)
    sys.exit(1)


def hexb(v):
    return "0x%02X" % v


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    src = pathlib.Path(sys.argv[1])
    if not src.is_file():
        die("not a file: %s" % src)
    raw = src.read_bytes()
    lines = raw.decode("utf-8", errors="replace").splitlines()

    start = next((i for i, l in enumerate(lines) if "lcd_init_cmds" in l and "[]" in l), None)
    if start is None:
        die("could not find 'lcd_init_cmds[]' in %s" % src)

    entries = []          # (cmd, [data bytes], delay_ms)
    mode = None           # None | 'rot' | 'else'
    seen_end = False
    for l in lines[start + 1:]:
        s = l.strip()
        if s.startswith("};"):
            seen_end = True
            break
        if not s or s == "{" or s.startswith("//"):
            continue
        if s.startswith("#ifdef EXAMPLE_Rotate_90"):
            mode = "rot"
            continue
        if s.startswith("#else") and mode == "rot":
            mode = "else"
            continue
        if s.startswith("#endif"):
            mode = None
            continue
        if mode == "rot":
            continue
        m = ENTRY.match(s)
        if not m:
            die("unparsed line in init table (refusing to silently skip it): %r" % s)
        cmd = int(m.group(1), 16)
        data = [int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]{2})", m.group(2))]
        declared = int(m.group(3))
        delay = int(m.group(4))
        if len(data) != declared:
            die("entry 0x%02X declares %d data bytes but lists %d" % (cmd, declared, len(data)))
        if delay > 255:
            die("delay %d ms on 0x%02X does not fit one byte" % (delay, cmd))
        entries.append((cmd, data, delay))
    if not seen_end:
        die("table terminator '};' not found")
    if not entries:
        die("no entries parsed")

    ops = ["BEGIN_WRITE",
           "WRITE_C8_D8, 0x36, 0x00",     # MADCTL, as the demo's wrapper sends first
           "WRITE_C8_D8, 0x3A, 0x55"]     # COLMOD 16 bpp, as the demo's wrapper sends next
    nbytes = 0
    for cmd, data, delay in entries:
        if len(data) == 0:
            ops.append("WRITE_COMMAND_8, %s" % hexb(cmd))
        elif len(data) == 1:
            ops.append("WRITE_C8_D8, %s, %s" % (hexb(cmd), hexb(data[0])))
        elif len(data) == 2:
            ops.append("WRITE_C8_D16, %s, %s, %s" % (hexb(cmd), hexb(data[0]), hexb(data[1])))
        else:
            ops.append("WRITE_COMMAND_8, %s, WRITE_BYTES, %d, %s"
                       % (hexb(cmd), len(data), ", ".join(hexb(b) for b in data)))
        nbytes += len(data)
        if delay > 0:
            ops.append("END_WRITE, DELAY, %d, BEGIN_WRITE" % delay)
    ops.append("END_WRITE")

    out = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else pathlib.Path(__file__).with_name("st77916_knob_init.h")
    sha = hashlib.sha256(raw).hexdigest()
    body = ",\n".join("    " + o for o in ops)
    text = (
        "// GENERATED by bringup/gen_init.py. Do not edit; do not commit.\n"
        "// Source: %s\n"
        "// Source SHA-256: %s\n"
        "// Table entries: %d, parameter bytes: %d\n"
        "// Contains Waveshare's panel init values. Their demo has no license file, so this\n"
        "// file is git-ignored on purpose. Regenerate it from the demo instead.\n"
        "#pragma once\n"
        "#include <Arduino_GFX_Library.h>\n\n"
        "static const uint8_t knob_st77916_init_ops[] = {\n%s};\n"
        % (src.name, sha, len(entries), nbytes, body + "\n")
    )
    out.write_text(text, encoding="utf-8", newline="\n")
    print("wrote %s" % out)
    print("  table entries : %d" % len(entries))
    print("  parameter bytes: %d" % nbytes)
    print("  op-array bytes : %d" % sum(1 for _ in re.findall(r"0x[0-9A-Fa-f]{2}|BEGIN_WRITE|END_WRITE|DELAY|WRITE_\w+|\b\d+\b", body)))
    print("  last command   : %s" % hexb(entries[-1][0]))
    print("  source sha256  : %s" % sha)
    return 0


if __name__ == "__main__":
    sys.exit(main())
